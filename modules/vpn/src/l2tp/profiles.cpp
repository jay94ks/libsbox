        /* Base64 of bytes. */
        std::string base64(std::string_view data) {
            certpp::CString out;
            if (!certpp::CBase64::encode(out, certpp::SReadOnlyByteSpan(reinterpret_cast<const uint8_t*>(data.data()), data.size()), false)) {
                return std::string();
            }

            return std::string(out.toPtr(), out.size());
        }

        /* Escapes XML text. */
        std::string xml(std::string_view text) {
            std::string out;
            for (char c : text) {
                switch (c) {
                case '&': out += "&amp;"; break;
                case '<': out += "&lt;"; break;
                case '>': out += "&gt;"; break;
                case '"': out += "&quot;"; break;
                case '\'': out += "&apos;"; break;
                default: out += c; break;
                }
            }

            return out;
        }

        /* PowerShell single-quoted string. */
        std::string ps(std::string_view text) {
            std::string out = "'";
            for (char c : text) {
                out += c == '\'' ? std::string("''") : std::string(1, c);
            }

            return out + "'";
        }

        /* Random version 4 UUID. */
        std::string uuid() {
            uint8_t b[16];
            IkeRandom(SByteSpan(b, sizeof(b)));
            b[6] = uint8_t((b[6] & 0x0f) | 0x40);
            b[8] = uint8_t((b[8] & 0x3f) | 0x80);
            char out[40];
            std::snprintf(out, sizeof(out), "%02X%02X%02X%02X-%02X%02X-%02X%02X-%02X%02X-%02X%02X%02X%02X%02X%02X", b[0], b[1], b[2], b[3],
                          b[4], b[5], b[6], b[7], b[8], b[9], b[10], b[11], b[12], b[13], b[14], b[15]);
            return out;
        }

        /* Reverse-DNS fragment. */
        std::string ident(std::string_view text) {
            std::string out;
            for (char c : text) {
                bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
                out += ok ? c : '-';
            }

            return out.empty() ? std::string("vpn") : out;
        }

        /* Windows -AuthenticationMethod value. */
        const char* windowsAuth(EPppAuth a) {
            switch (a) {
            case EPPPA_PAP: return "Pap";
            case EPPPA_CHAP_MD5: return "Chap";
            default: return "MSChapv2";
            }
        }

